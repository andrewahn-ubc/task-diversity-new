td2_install_signal_forwarders() {
  TD2_ACTIVE_CHILD=''
  trap 'if [[ -n ${TD2_ACTIVE_CHILD:-} ]]; then kill -USR1 "$TD2_ACTIVE_CHILD" 2>/dev/null || true; fi' USR1
  trap 'if [[ -n ${TD2_ACTIVE_CHILD:-} ]]; then kill -TERM "$TD2_ACTIVE_CHILD" 2>/dev/null || true; fi' TERM INT
}

td2_run_checkpointable() {
  "$@" &
  TD2_ACTIVE_CHILD=$!
  local rc
  while true; do
    set +e
    wait "$TD2_ACTIVE_CHILD"
    rc=$?
    set -e
    if ! kill -0 "$TD2_ACTIVE_CHILD" 2>/dev/null; then
      TD2_ACTIVE_CHILD=''
      return "$rc"
    fi
    # wait(1) was interrupted by a signal, while the Python process is still
    # atomically checkpointing.  Wait again instead of exiting the batch job.
  done
}

td2_accept_watchdog_exit() {
  local status=$1
  local batch_started_epoch=$2
  local soft_limit=$3
  if ((status == 0)); then
    return 0
  fi
  case $status in
    124|137|138) ;;
    *) td2_die "training process failed with exit status $status" ;;
  esac

  local elapsed_seconds=$(( $(date +%s) - batch_started_epoch ))
  ((elapsed_seconds + 5 >= soft_limit)) || td2_die \
    "training process exited with status $status before the watchdog deadline"
  td2_note \
    "watchdog stopped a long accelerator operation with status $status; requeuing from the last durable state"
}

td2_write_receipt() {
  local destination=$1
  shift
  local tmp="${destination}.tmp.${SLURM_JOB_ID:-$$}"
  {
    printf 'created_utc=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '%s\n' "$@"
  } >"$tmp"
  mv -f -- "$tmp" "$destination"
}
