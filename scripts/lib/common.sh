#!/usr/bin/env bash

# Shared, side-effect-free helpers for the Compute Canada launch scripts.
# This file is sourced; callers are responsible for enabling strict mode.

td2_die() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

td2_note() {
  printf '[td2] %s\n' "$*"
}

td2_require_command() {
  command -v "$1" >/dev/null 2>&1 || td2_die "required command not found: $1"
}

td2_require_uint() {
  local label=$1
  local value=$2
  [[ $value =~ ^[0-9]+$ ]] || td2_die "$label must be a non-negative integer (got: $value)"
}

td2_repo_root() {
  local common_dir
  common_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
  cd -- "$common_dir/../.." && pwd -P
}

td2_runtime_env_path() {
  local repo_root=$1
  printf '%s\n' "${TD2_RUNTIME_ENV:-$repo_root/.runtime/compute-canada/runtime.env}"
}

td2_load_runtime() {
  local repo_root=$1
  local runtime_env
  runtime_env=$(td2_runtime_env_path "$repo_root")
  [[ -f $runtime_env ]] || td2_die \
    "runtime environment not found at $runtime_env; run scripts/setup_compute_canada.sh first"
  # runtime.env is generated by setup_compute_canada.sh with shell-escaped,
  # absolute paths and contains exports only.
  # shellcheck disable=SC1090
  source "$runtime_env"
  export TD2_RUNTIME_ENV="$runtime_env"
  [[ ${TD2_REPO_ROOT:-} == "$repo_root" ]] || td2_die \
    "runtime was built for '${TD2_REPO_ROOT:-unset}', not '$repo_root'"
  [[ -x ${TD2_VENV_DIR:-}/bin/python ]] || td2_die \
    "virtual environment is missing or incomplete: ${TD2_VENV_DIR:-unset}"
}

td2_load_profile() {
  local repo_root=$1
  local profile=$2
  [[ $profile =~ ^(narval|rorqual)$ ]] || td2_die \
    "cluster must be 'narval' or 'rorqual' (got: $profile)"
  local profile_file="$repo_root/slurm/profiles/$profile.env"
  [[ -f $profile_file ]] || td2_die "missing cluster profile: $profile_file"
  # The profile files are version-controlled constant assignments.
  # shellcheck disable=SC1090
  source "$profile_file"
  [[ ${TD2_PROFILE_NAME:-} == "$profile" ]] || td2_die "invalid profile: $profile_file"
}

td2_activate_runtime() {
  module --force purge
  # A caller-exported CUDA/cuDNN path can survive an Lmod purge. Clear it before
  # loading the standard modules so JAX's bundled CUDA libraries are not
  # shadowed, while preserving any library path the standard modules then add.
  unset LD_LIBRARY_PATH
  module load StdEnv/2023
  module load python/3.13.2
  # Do not let login-shell or module Python/JAX overrides leak into the pinned
  # runtime. The virtual environment and assignments below are the sole source
  # of package and accelerator configuration inside jobs.
  unset PYTHONPATH PYTHONHOME XLA_FLAGS JAX_PLATFORMS JAX_PLATFORM_NAME
  unset JAX_DISABLE_JIT JAX_ENABLE_X64 JAX_DEBUG_NANS JAX_DEBUG_INFS
  unset CUDA_HOME CUDA_PATH
  # shellcheck disable=SC1090
  source "$TD2_VENV_DIR/bin/activate"

  export PYTHONNOUSERSITE=1
  # Execute the checked-out experiment code while retaining the pinned binary
  # dependencies in the durable venv. A normal git pull therefore does not
  # require rebuilding the runtime when requirements have not changed.
  export PYTHONPATH="$TD2_REPO_ROOT/src"
  export PIP_NO_INDEX=1
  export PIP_DISABLE_PIP_VERSION_CHECK=1
  export WANDB_MODE=offline
  export WANDB_SILENT=true
  export HF_HUB_OFFLINE=1
  export JAX_PLATFORMS=cuda
  export XLA_PYTHON_CLIENT_PREALLOCATE=false
  mkdir -p -- "$TD2_RUNTIME_ROOT/jax-cache"
  export JAX_COMPILATION_CACHE_DIR="$TD2_RUNTIME_ROOT/jax-cache"
}

td2_parse_job_id() {
  # --parsable can return either JOBID or JOBID;CLUSTER.
  local submitted=$1
  local job_id=${submitted%%;*}
  [[ $job_id =~ ^[0-9]+(_[0-9]+)?$ ]] || td2_die \
    "could not parse Slurm job id from: $submitted"
  printf '%s\n' "$job_id"
}

td2_build_gpu_sbatch_args() {
  TD2_GPU_SBATCH_ARGS=(
    "--nodes=1"
    "--ntasks=1"
    "--cpus-per-task=$TD2_CPUS_PER_GPU"
    "--mem=$TD2_MEMORY_PER_GPU"
    "--gpus-per-node=$TD2_GPU_REQUEST"
  )
}

td2_stream_dir() {
  local output_root=$1 algorithm=$2 diversity=$3 seed=$4
  printf '%s/%s/diversity_%s/seed_%s\n' "$output_root" "$algorithm" "$diversity" "$seed"
}

